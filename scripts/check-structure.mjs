import fs from 'node:fs';
import assert from 'node:assert/strict';
const read = name=>fs.readFileSync(new URL(`../${name}`,import.meta.url),'utf8');
const editor=read('src/editor.jsx');
const store=read('src/content-store.jsx');
const rules=read('firestore.rules');
const app=read('src/main.jsx');
assert(store.includes('new GoogleAuthProvider()'),'Login Google assente');
assert(store.includes("doc(db, 'admins', next.uid)"),'Controllo UID GM assente');
assert(store.includes("collection(db,'drafts')"),'Bozze assenti');
assert(store.includes("collection(db,'revisions')"),'Cronologia assente');
assert(store.includes('bootstrap'),'Importazione iniziale assente');
assert(editor.includes('validatedImageUrl'),'Immagini da URL assenti');
assert(editor.includes('Salva bozza')&&editor.includes('Pubblica'),'Comandi editore assenti');
assert(!editor.includes('uploadBytes')&&!store.includes('firebase/storage'),'Non usare Firebase Storage');
assert(rules.includes('request.auth.uid')&&rules.includes('.data.enabled == true'),'Autorizzazione server insufficiente');
assert(rules.includes('allow read, write: if gm();'),'Protezione bozze assente');
assert(!rules.includes('allow write: if true')&&!rules.includes('allow read, write: if true'),'Regole aperte');
assert(app.includes('ContentProvider')&&app.includes('GenericPage'),'Integrazione mancante');
assert(app.includes('<HomeConnectionPreview theme={theme}/>'),'Anteprima atlante mancante dalla Home');
assert(!app.includes("[RELATIONS, 'CONNESSIONI']"),'Connessioni non deve apparire nella navigazione primaria');
console.log('OK — editor GM, bozze/pubblicazione, cronologia, URL immagini, anteprima Home e regole Firestore presenti.');
