import assert from 'node:assert/strict';
import fs from 'node:fs';
import {expandCounterbodyPages,COUNTERBODY_SECTIONS,isCounterbodySubsection} from '../src/counterbody-sections.js';
import {createsPeriodCycle,buildPeriodForest} from '../src/storia-periods.js';
const app=fs.readFileSync('src/main.jsx','utf8');
const store=fs.readFileSync('src/content-store.jsx','utf8');
const history=fs.readFileSync('src/StoriaTimeline.jsx','utf8');
const homeCss=fs.readFileSync('src/layout-v35.css','utf8');
const historyCss=fs.readFileSync('src/storia-timeline.css','utf8');
assert.equal(COUNTERBODY_SECTIONS.length,6);
assert.equal(isCounterbodySubsection('Hybrid'),false);
for(const title of COUNTERBODY_SECTIONS)assert.ok(isCounterbodySubsection(title));
const original={id:'controcorpi',kind:'chapter',title:'Controcorpi',topics:[...COUNTERBODY_SECTIONS.map(name=>({name})),{name:'Hybrid'}],blocks:[{id:'markdown',type:'rich',html:'<h3 id="vessel">Vessel</h3><p>Testo proprietario.</p><h3 id="hybrid">Hybrid</h3><p>Combinazioni.</p>'}]};
const expanded=expandCounterbodyPages([original]);
assert.equal(expanded.length,7,'6 sottosezioni vere, non 7');
for(const name of COUNTERBODY_SECTIONS){const section=expanded.find(p=>p.id==='controcorpi-'+name.toLowerCase());assert.equal(section?.parentId,'controcorpi');assert.equal(section?.kind,'collection');}
assert.match(expanded.find(p=>p.id==='controcorpi-vessel').blocks[0].html,/Testo proprietario/,'Conserva descrizioni contenute nella vecchia pagina');
assert.ok(!expanded.some(p=>p.title==='Hybrid'));
const persisted={id:'controcorpi-vessel',kind:'collection',title:'Vessel',parentId:'controcorpi',blocks:[]};
assert.equal(expandCounterbodyPages([original,persisted]).filter(p=>p.id==='controcorpi-vessel').length,1,'La pubblicazione GM sostituisce la sottosezione virtuale');
assert.match(app,/filter\(chapter=>entry.layout!==.counterbodies.\|\|!isCounterbodySubsection/,'I sei capitoli migrano fuori dall’articolo padre');
assert.match(app,/featured:false/,'Alchimia non è permanentemente evidenziata');
assert.match(app,/const shownRoots=ready\?roots:initialSections/,'Le sette tessere sono stabili finché Firestore carica');
assert.match(store,/configLoaded/);assert.match(store,/expandCounterbodyPages/);
assert.match(homeCss,/animation:none!important/);
const periods=[{id:'a',title:'Era dei Poteri',builtin:true,parentPeriodId:''},{id:'b',title:'Prima epoca',parentPeriodId:'a',rank:2},{id:'c',title:'Seconda epoca',parentPeriodId:'b',rank:0}];
const forest=buildPeriodForest(periods,[{id:'e',timeline:{periodId:'c',year:null}}],[]);
assert.equal(forest.periods[0].children[0].children[0].events[0].id,'e','Periodi annidati anche senza anni');
assert.equal(createsPeriodCycle('a','c',periods),true,'Blocca un ciclo di 3 periodi');
assert.equal(createsPeriodCycle('c','a',periods),false,'Consente spostamenti validi');
assert.equal(createsPeriodCycle('b','b',periods),true);
assert.match(history,/parentPeriodId/);assert.match(history,/renderPeriod\(child,depth\+1\)/);
assert.match(history,/Periodo contenitore \(facoltativo\)/);
assert.match(historyCss,/storia-period-children/);
console.log('OK — v3.5: 6 sottosezioni Controcorpi, Hybrid nell’introduzione, Home stabile e periodi storici annidabili senza anni.');
