import assert from 'node:assert/strict';
import fs from 'node:fs';
import {assertTreeMove,descendantsOf,editableTreeEntries,getEntryPath,isContainer,LOCKED_TREE_IDS,treeGroups} from '../src/collection-tree.js';
import {insertionOrder} from '../src/import-utils.js';

const read=path=>fs.readFileSync(new URL(`../${path}`,import.meta.url),'utf8');
const examples=JSON.parse(read('esempi-importazione/BTO-Lore-v3.1-Riorganizzato.json')).entries;
const base=editableTreeEntries(examples);
const governments=base.find(e=>e.id==='organizzazioni-governi');
assert.ok(governments&&isContainer(governments));
assert.ok(base.some(e=>e.id==='personaggio-re-italia'&&e.parentId===governments.id));
assert.ok(base.some(e=>e.id==='personaggio-ivory-covenant'&&e.parentId===governments.id));
const kingdom={id:'collection-regno-italiano',kind:'collection',title:'Regno Italiano',parentId:governments.id,order:80};
const entries=[...base,kingdom];
assert.equal(assertTreeMove(entries,'personaggio-re-italia',kingdom.id).id,'personaggio-re-italia');
assert.equal(assertTreeMove(entries,'personaggio-ivory-covenant',kingdom.id).id,'personaggio-ivory-covenant');
assert.ok(getEntryPath(entries,kingdom.id).map(e=>e.title).includes('Governi e Strutture Extra Governative'));
assert.throws(()=>assertTreeMove(entries,kingdom.id,kingdom.id),/interno|sottoraccolta/);
assert.throws(()=>assertTreeMove(entries,governments.id,kingdom.id),/interno|sottoraccolta/);
assert.throws(()=>assertTreeMove(entries,kingdom.id,'personaggio-re-italia'),/raccolta|sezione/);
assert.throws(()=>assertTreeMove(entries,'personaggio-re-italia','root'),/pagine devono appartenere/);
assert.throws(()=>assertTreeMove(entries,'organizzazioni','root'),/strutturale/);
assert.ok(LOCKED_TREE_IDS.has('alchimia-materiali'));
assert.ok(descendantsOf(entries,'organizzazioni').has(kingdom.id));
const groups=treeGroups(entries);assert.ok(groups.get(governments.id)?.some(e=>e.id===kingdom.id));
const siblings=groups.get(governments.id);assert.ok(Number.isFinite(insertionOrder(siblings,0)));
const orphan={id:'orfano',kind:'page',parentId:'raccolta-non-esistente',title:'Orfano'};
assert.ok(treeGroups([...entries,orphan]).get('__orphans__').some(e=>e.id==='orfano'));

const main=read('src/main.jsx'),editor=read('src/editor.jsx'),manager=read('src/CollectionManager.jsx'),store=read('src/content-store.jsx'),css=read('src/collection-manager.css');
assert.match(main,/<GMCollectionActions entry=\{entry\}/);
assert.match(main,/import '\.\/collection-manager\.css'/);
assert.match(editor,/Nuova sottoraccolta/);
assert.match(editor,/Gestisci raccolte e pagine/);
assert.match(manager,/onDragStart/);
assert.match(manager,/onDrop/);
assert.match(manager,/Sposta nella raccolta/);
assert.match(manager,/Crea e pubblica/);
assert.match(manager,/Su<\/button>| Su<\/button>/);
assert.match(manager,/Giù<\/button>/);
assert.match(store,/async function moveEntry\(/);
assert.match(store,/transaction\.update\(recordRef,patch\)/);
assert.match(store,/transaction\.update\(draftRef,patch\)/);
assert.match(store,/action:'tree-move'/);
assert.ok(!manager.includes('note-store')&&!manager.includes('PlayerNotes'));
assert.match(css,/@media\(max-width:790px\)/);
console.log('OK — v3.11: raccolte annidate, navigazione ad albero, spostamento pagine e bozze, prevenzione cicli, UI mobile.');
